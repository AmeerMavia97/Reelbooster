export const translations: Record<Locale, Record<string, string>> = {
  en: {},
  tr,
};

export function translateText(value: string, locale: Locale): string {
  if (locale === "en") return value;

  const match = value.match(/^(\s*)(.*?)(\s*)$/s);
  const leading = match?.[1] ?? "";
  const text = match?.[2] ?? value;
  const trailing = match?.[3] ?? "";

  if (!text) return value;

  const translated = translations[locale][text];
  if (translated) return `${leading}${translated}${trailing}`;

  const withoutColon = text.endsWith(":") ? text.slice(0, -1) : "";
  if (withoutColon && translations[locale][withoutColon]) {
    return `${leading}${translations[locale][withoutColon]}:${trailing}`;
  }

  return value;
}
